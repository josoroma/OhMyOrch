    ("ohmyorch-product-manager", "Product Manager", "selection, <code>status.md</code>, archive, story status"),
    ("ohmyorch-planner", "Planner", "<code>implementation-plan.md</code>, returned to <code>/ohmyorch-plan-feature</code>"),
