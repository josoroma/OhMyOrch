hook_rows = []
settings = _json.load(open(os.path.join(ROOT, ".claude/settings.json")))
for ev, arr in settings["hooks"].items():
    for h in arr:
        for x in h["hooks"]:
            m = re.search(r"scripts/([a-z-]+\.sh)", x["command"])
            scr = m.group(1) if m else "?"
            what = BLOCKS.get(scr, "")
            if scr == "guard-delivery-loop.sh":
                what = ("ending the turn while an ACTIVE goal has work left" if ev == "Stop"
                        else "a main-session write to <code>review.md</code> / <code>test-report.md</code> while a goal is ACTIVE")
            hook_rows.append(f'          <tr><td><code>{ev}</code></td><td><code>{E(h.get("matcher", "—") or "—")}</code></td><td><code>{scr}</code></td><td><code>.claude/settings.json</code></td><td>{what}</td></tr>')
for a in ["ohmyorch-implementer", "ohmyorch-reviewer", "ohmyorch-tester"]:
    hook_rows.append(f'          <tr><td><code>PreToolUse</code></td><td><code>Write|Edit|MultiEdit</code></td><td><code>check-write-scope.sh --role {a}</code></td><td><code>.claude/agents/{a}.md</code></td><td>a {a} write outside its scope</td></tr>')

