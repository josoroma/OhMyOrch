#!/usr/bin/env python3
"""Build docs/pages/harness-overview.html from scripts/templates/html-page.html.

The template's <head> (Luma tokens, styles, pre-paint theme script) and its closing
toggle script are kept verbatim; only the body between <main> and the footer changes.
Every figure and inventory table is recomputed from the repository on each run.

Usage: python3 scripts/pages/make-harness-overview.py
       scripts/validate-html-page.sh --page docs/pages/harness-overview.html
"""
import base64, os, re, subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
tpl = open(os.path.join(ROOT, "scripts/templates/html-page.html")).read()

TITLE = "OhMyOrch Harness — Overview and Status"
SUMMARY = ("How the harness turns a SPECS.md backlog into delivered, reviewed, and "
           "tested OpenSpec changes, and where the backlog stands today.")

head = tpl[: tpl.index("<body>")]
head = head.replace("{{TITLE}}", TITLE).replace("{{SUMMARY}}", SUMMARY)
# Drop the template's authoring comment: it describes the template, not this page.
c0 = head.index("<!--"); c1 = head.index("-->", c0) + 3
head = head[:c0] + "<!-- Generated by /ohmyorch-generate-html-page (US-14.1). Figures: see section#sources. -->" + head[c1:]
tail = tpl[tpl.index("<script>\n  /* Theme toggle"):]

def sh(cmd):
    return subprocess.run(cmd, shell=True, cwd=ROOT, capture_output=True, text=True).stdout.strip()

epics = int(sh("grep -cE '^# EPIC-[0-9]+:' SPECS.md"))
stories = int(sh(r"grep -cE '^### US-[0-9]+\.[0-9]+:' SPECS.md"))
done = int(sh("grep -c '^Status: DONE' SPECS.md"))
inprog = int(sh("grep -c '^Status: IN PROGRESS' SPECS.md || true") or 0)
archived = int(sh("ls openspec/changes/archive | wc -l"))
caps = int(sh("ls openspec/specs | wc -l"))
agents = int(sh("ls .claude/agents/*.md | grep -vc README"))
skills = int(sh("ls .claude/skills | wc -l"))
rules = int(sh("ls .claude/rules/*.md | grep -vc README"))
date = sh("date +%Y-%m-%d")
with open(os.path.join(ROOT, "docs/images/OhMyOrch.png"), "rb") as fh:
    logo = "data:image/png;base64," + base64.b64encode(fh.read()).decode("ascii")
pct = round(100 * done / stories) if stories else 0

epic_rows = []
for e in range(1, epics + 1):
    t = sh(f"grep -E '^# EPIC-{e}:' SPECS.md | sed 's/^# EPIC-[0-9]*: //'")
    awk = ("awk -v e=EPIC-%d '/^# EPIC-/{c=$2; sub(/:$/,\"\",c)} /^### US-/{if(c==e)n++} "
           "/^Status: DONE/{if(c==e)d++} END{print n+0, d+0}' SPECS.md") % e
    n, d = map(int, sh(awk).split())
    badge = ('<span class="badge badge-success">DONE</span>' if n == d
             else '<span class="badge badge-primary">IN PROGRESS</span>')
    epic_rows.append(f'          <tr><td>EPIC-{e}</td><td>{t}</td><td class="num">{d} / {n}</td><td>{badge}</td></tr>')

suites = []
for s in ["write-scope", "guards", "status", "completion", "delivery", "html-page", "harness-reset"]:
    if not os.path.exists(os.path.join(ROOT, f"scripts/test-{s}.sh")):
        continue
    out = sh(f"scripts/test-{s}.sh 2>&1 | sed -n 's/^  passed: //p;s/^  failed: /F/p'")
    parts = out.split()
    p = parts[0] if parts else "unknown"
    f = parts[1][1:] if len(parts) > 1 else "unknown"
    badge = ('<span class="badge badge-success">PASS</span>' if f == "0"
             else '<span class="badge badge-danger">FAIL</span>')
    suites.append((s, p, f, badge))
total = sum(int(p) for _, p, _, _ in suites if p.isdigit())
suite_rows = "\n".join(
    f'          <tr><td><code>scripts/test-{s}.sh</code></td><td class="num">{p}</td><td class="num">{f}</td><td>{b}</td></tr>'
    for s, p, f, b in suites)

import html as _html, json as _json
E = _html.escape

def front(path, key):
    return sh("awk '/^---/{n++; next} n==1' " + path + " | sed -n 's/^" + key + ": //p' | head -1")

# ---- Harness inventory (from .claude/ and scripts/) -------------------------
n_cmds = int(sh("ls .claude/commands/ohmyorch/opsx/*.md | wc -l"))
n_hooks = int(sh("python3 -c \"import json;d=json.load(open('.claude/settings.json'));print(sum(len(h['hooks']) for a in d['hooks'].values() for h in a))\""))
n_agent_hooks = int(sh("grep -l -E 'check-write-scope.sh[^a-z]*--role' .claude/agents/*.md | grep -v README | wc -l"))
n_guards = int(sh("ls scripts/guard-*.sh | wc -l")) + 1
n_validators = int(sh("ls scripts/validate-*.sh | wc -l"))
n_suites = int(sh("ls scripts/test-*.sh | wc -l"))
n_skills_os = int(sh("ls -d .claude/skills/ohmyorch-openspec-* | wc -l"))
n_skills_h = skills - n_skills_os

