    ("ohmyorch-codebase-analyst", "Codebase Analyst", "<code>CODEBASE.md</code>, returned to <code>/ohmyorch-analyze-codebase</code>"),
    ("ohmyorch-product-specifier", "Product Specifier", "<code>PRD.md</code>, returned to <code>/ohmyorch-generate-prd</code>"),
